/*
  NOVA videotron package — After Effects importer
  Generated by src/build_ae.py

  What it does
  1. Imports the PNG sequences as single footage items (not 360 loose files).
  2. Sets straight alpha, frame rate and duration correctly.
  3. Builds a 12 s main comp and a 6 s lower-third comp.
  4. Adds editorial markers and a non-rendering 5% safe-area guide.

  Run: File > Scripts > Run Script File...
*/

(function () {
    var WIDTH = 1920;
    var HEIGHT = 1080;
    var FPS = 30;
    var MAIN_DURATION = 12.0;
    var LOWER_DURATION = 6.0;
    var SAFE = 0.05;
    var ROOT = File($.fileName).parent.parent.fsName;

    var mainFirst = new File(ROOT + "/out/main_loop/png/main_loop_0000.png");
    var lowerFirst = new File(ROOT + "/out/lower_third/png/lower_third_0000.png");

    if (!mainFirst.exists) {
        alert("Main PNG sequence not found:\n" + mainFirst.fsName + "\n\nRun: python3 src/render.py --scene all");
        return;
    }

    app.beginUndoGroup("Import NOVA videotron package");

    // Reuse the folder if the script is run more than once.
    var folder = null;
    for (var i = 1; i <= app.project.numItems; i++) {
        var item = app.project.item(i);
        if (item instanceof FolderItem && item.name === "NOVA - Videotron Package") {
            folder = item;
            break;
        }
    }
    if (!folder) {
        folder = app.project.items.addFolder("NOVA - Videotron Package");
    }

    function importSequence(firstFile, name, alphaMode) {
        var io = new ImportOptions(firstFile);
        io.sequence = true;
        var footage = app.project.importFile(io);
        footage.name = name;
        footage.parentFolder = folder;
        footage.interpretation.frameRate = FPS;
        if (alphaMode !== null) {
            footage.interpretation.alphaMode = alphaMode;
        }
        return footage;
    }

    var mainFootage = importSequence(mainFirst, "NOVA_MainLoop_PNG_" + WIDTH + "x" + HEIGHT, null);
    var mainComp = app.project.items.addComp(
        "NOVA_Main_" + Math.round(MAIN_DURATION) + "s",
        WIDTH, HEIGHT, 1.0, MAIN_DURATION, FPS
    );
    mainComp.parentFolder = folder;
    mainComp.bgColor = [0, 0, 0];

    var mainLayer = mainComp.layers.add(mainFootage);
    mainLayer.name = "NOVA / MAIN LOOP — PNG sequence";
    mainLayer.startTime = 0;
    mainLayer.inPoint = 0;
    mainLayer.outPoint = MAIN_DURATION;

    // Markers make the edit points obvious to another artist.
    var mainMarkers = [
        [0.0, "01 / SIGNAL"],
        [0.65, "02 / MARK + WORDMARK"],
        [4.55, "03 / KINETIC TYPE"],
        [7.85, "04 / LOCKUP"],
        [11.6, "05 / LOOP TAIL"]
    ];
    var mainStretch = MAIN_DURATION / 12.0;
    for (var m = 0; m < mainMarkers.length; m++) {
        mainComp.markerProperty.setValueAtTime(
            mainMarkers[m][0] * mainStretch,
            new MarkerValue(mainMarkers[m][1])
        );
    }

    function addSafeGuide(comp) {
        var guide = comp.layers.addShape();
        guide.name = "GUIDES - 5% title safe (does not render)";
        guide.guideLayer = true;
        guide.property("ADBE Transform Group").property("ADBE Position").setValue([WIDTH / 2, HEIGHT / 2]);

        var rootVectors = guide.property("ADBE Root Vectors Group");
        var vectorGroup = rootVectors.addProperty("ADBE Vector Group");
        var contents = vectorGroup.property("ADBE Vectors Group");
        var rect = contents.addProperty("ADBE Vector Shape - Rect");
        rect.property("ADBE Vector Rect Size").setValue([
            WIDTH * (1 - SAFE * 2),
            HEIGHT * (1 - SAFE * 2)
        ]);
        rect.property("ADBE Vector Rect Position").setValue([0, 0]);
        var stroke = contents.addProperty("ADBE Vector Graphic - Stroke");
        stroke.property("ADBE Vector Stroke Color").setValue([1, 0.22, 0.42]);
        stroke.property("ADBE Vector Stroke Width").setValue(2);
        guide.locked = true;
    }

    addSafeGuide(mainComp);

    // Lower third (straight alpha, transparent comp).
    var lowerComp = null;
    if (lowerFirst.exists) {
        var lowerFootage = importSequence(lowerFirst, "NOVA_LowerThird_PNG_" + WIDTH + "x" + HEIGHT, AlphaMode.STRAIGHT);
        lowerComp = app.project.items.addComp(
            "NOVA_LowerThird_" + Math.round(LOWER_DURATION) + "s",
            WIDTH, HEIGHT, 1.0, LOWER_DURATION, FPS
        );
        lowerComp.parentFolder = folder;
        lowerComp.bgColor = [0, 0, 0];

        var lowerLayer = lowerComp.layers.add(lowerFootage);
        lowerLayer.name = "NOVA / LOWER THIRD — straight alpha";
        lowerLayer.startTime = 0;
        lowerLayer.inPoint = 0;
        lowerLayer.outPoint = LOWER_DURATION;

        var lowerStretch = LOWER_DURATION / 6.0;
        lowerComp.markerProperty.setValueAtTime(0.0, new MarkerValue("IN"));
        lowerComp.markerProperty.setValueAtTime(1.2 * lowerStretch, new MarkerValue("HOLD"));
        lowerComp.markerProperty.setValueAtTime(4.86 * lowerStretch, new MarkerValue("OUT"));

        addSafeGuide(lowerComp);
    }

    app.endUndoGroup();

    var message = "NOVA videotron package imported.\n\n"
        + "- NOVA_Main_" + Math.round(MAIN_DURATION) + "s - full-frame loop\n"
        + "- NOVA_LowerThird_" + Math.round(LOWER_DURATION) + "s - transparent overlay\n\n"
        + "Both comps use PNG sequences with straight alpha. The red guide is a non-rendering 5% title-safe check.\n\n"
        + "For a self-contained master, use the ProRes files in out/.";
    alert(message);
})();
